import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "Sources", "NotasWorkflowMac", "Translations.swift")
NAME_NVDA = "Notas Workflow NVDA"
NAME_MAC = "Notas Workflow Mac"

#: Texts of the Mac version (menus, settings and dialogs that NVDA gave to the add-on).
MAC_ONLY = {
	"Settings": "Configurações",
	"Settings…": "Configurações…",
	"Open at &login": "Abrir ao iniciar &sessão",
	"Could not change the opening at login.": "Não foi possível mudar a abertura ao iniciar a sessão.",
	"About {name}": "Sobre o {name}",
	"Hide {name}": "Ocultar o {name}",
	"Quit {name}": "Encerrar o {name}",
	"Edit": "Editar",
	"Undo": "Desfazer",
	"Redo": "Refazer",
	"Cut": "Recortar",
	"Copy": "Copiar",
	"Paste": "Colar",
	"Select All": "Selecionar tudo",
	"Notes": "Folhas",
	"Say how many notes each lane has": "Dizer quantas folhas cada raia tem",
	"Window": "Janela",
	"Minimize": "Minimizar",
	"Yes": "Sim",
	"No": "Não",
}


def readPo(path):
	"""{msgid: msgstr} of a .po file (single and multi-line strings)."""
	pairs = {}
	msgid = msgstr = None
	current = None
	with open(path, encoding="utf-8") as f:
		for raw in f:
			line = raw.strip()
			if line.startswith("msgid "):
				if msgid is not None and msgstr is not None:
					pairs[msgid] = msgstr
				msgid = ast.literal_eval(line[6:])
				msgstr = None
				current = "id"
			elif line.startswith("msgstr "):
				msgstr = ast.literal_eval(line[7:])
				current = "str"
			elif line.startswith('"') and current:
				part = ast.literal_eval(line)
				if current == "id":
					msgid += part
				else:
					msgstr += part
			else:
				current = None if not line else current
	if msgid is not None and msgstr is not None:
		pairs[msgid] = msgstr
	pairs.pop("", None)
	return pairs


def swiftString(text):
	out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
	return '"%s"' % out


def main():
	if len(sys.argv) != 2:
		sys.exit("Uso: python3 tools/gerar_traducoes.py <caminho do nvda.po>")
	pairs = readPo(sys.argv[1])
	pairs.update(MAC_ONLY)
	lines = [
		"// Notas Workflow Mac - Translations.swift",
		"// GENERATED by tools/gerar_traducoes.py from the nvda.po of NotasWorkflowNVDA. Do not edit by hand.",
		"// Copyright (C) 2026 Wellington Cruz <weliveiracruz@gmail.com>",
		"// This file is covered by the GNU General Public License, version 2.",
		"",
		"import Foundation",
		"",
		"enum Translations {",
		"\t/// Portuguese when the first language of the Mac is Portuguese; otherwise the English keys.",
		"\tstatic let current: [String: String] = {",
		"\t\tlet language = Locale.preferredLanguages.first ?? \"en\"",
		"\t\tvar table = language.hasPrefix(\"pt\") ? portuguese : [:]",
		"\t\t// The English texts keep the name of the Mac version too.",
		"\t\tfor key in portuguese.keys where key.contains(%s) && table[key] == nil {" % swiftString(NAME_NVDA),
		"\t\t\ttable[key] = key.replacingOccurrences(of: %s, with: %s)" % (swiftString(NAME_NVDA), swiftString(NAME_MAC)),
		"\t\t}",
		"\t\treturn table",
		"\t}()",
		"",
		"\tstatic let portuguese: [String: String] = [",
	]
	for key in sorted(pairs):
		value = pairs[key].replace(NAME_NVDA, NAME_MAC)
		lines.append("\t\t%s: %s," % (swiftString(key), swiftString(value)))
	lines += ["\t]", "}", ""]
	with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
		f.write("\n".join(lines))
	print("%d textos gravados em %s" % (len(pairs), os.path.normpath(TARGET)))


if __name__ == "__main__":
	main()
